const { jsPDF } = require('jspdf');
const { marked } = require('marked');

class SimplePDFService {
  constructor() {
    this.configureMarked();
  }

  configureMarked() {
    marked.setOptions({
      breaks: true,
      gfm: true
    });
  }

  async generatePDF(content, title, userEmail = null) {
    try {
      console.log(`Generating PDF for '${title}' using jsPDF`);
      
      // Create new PDF document
      const doc = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
      });

      // Set up document properties
      doc.setProperties({
        title: title,
        creator: 'CodeTutor AI',
        author: userEmail || 'CodeTutor AI'
      });

      let yPosition = 20;
      const pageHeight = doc.internal.pageSize.height;
      const pageWidth = doc.internal.pageSize.width;
      const margin = 20;
      const maxWidth = pageWidth - (margin * 2);

      // Add header
      doc.setFontSize(22);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(31, 41, 55); // #1f2937
      
      // Title
      const titleLines = doc.splitTextToSize(title, maxWidth);
      doc.text(titleLines, margin, yPosition);
      yPosition += titleLines.length * 8;
      
      // Subtitle
      yPosition += 5;
      doc.setFontSize(12);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(107, 114, 128); // #6b7280
      doc.text('Professional Tutorial Documentation', margin, yPosition);
      yPosition += 15;

      // Add separator line
      doc.setDrawColor(229, 231, 235); // #e5e7eb
      doc.line(margin, yPosition, pageWidth - margin, yPosition);
      yPosition += 10;

      // Parse and add content
      const tokens = marked.lexer(content);
      yPosition = this.renderTokens(doc, tokens, yPosition, margin, maxWidth, pageHeight);

      // Add footer
      const currentDate = new Date().toLocaleDateString('en-US', {
        year: 'numeric',
        month: 'long',
        day: 'numeric'
      });

      const footerText = userEmail ? `Generated by ${userEmail}` : 'Generated by CodeTutor AI';
      
      // Footer line
      const footerY = pageHeight - 20;
      doc.setDrawColor(229, 231, 235);
      doc.line(margin, footerY - 5, pageWidth - margin, footerY - 5);
      
      // Footer text
      doc.setFontSize(9);
      doc.setTextColor(107, 114, 128);
      doc.text(footerText, margin, footerY);
      doc.text(currentDate, pageWidth - margin - doc.getTextWidth(currentDate), footerY);

      // Add page numbers
      const pageCount = doc.internal.getNumberOfPages();
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(9);
        doc.setTextColor(156, 163, 175); // #9ca3af
        const pageText = `${i} / ${pageCount}`;
        doc.text(pageText, pageWidth - margin - doc.getTextWidth(pageText), footerY + 8);
      }

      // Return PDF as buffer
      const pdfBuffer = Buffer.from(doc.output('arraybuffer'));
      console.log(`Successfully generated PDF: ${pdfBuffer.length} bytes`);
      return pdfBuffer;
      
    } catch (error) {
      console.error('Error generating PDF with jsPDF:', error);
      throw new Error(`PDF generation failed: ${error.message}`);
    }
  }

  renderTokens(doc, tokens, yPosition, margin, maxWidth, pageHeight) {
    tokens.forEach((token) => {
      // Check if we need a new page
      if (yPosition > pageHeight - 40) {
        doc.addPage();
        yPosition = 20;
      }

      switch (token.type) {
        case 'heading':
          yPosition = this.renderHeading(doc, token, yPosition, margin, maxWidth);
          break;
        case 'paragraph':
          yPosition = this.renderParagraph(doc, token, yPosition, margin, maxWidth);
          break;
        case 'code':
          yPosition = this.renderCodeBlock(doc, token, yPosition, margin, maxWidth);
          break;
        case 'list':
          yPosition = this.renderList(doc, token, yPosition, margin, maxWidth);
          break;
        case 'blockquote':
          yPosition = this.renderBlockquote(doc, token, yPosition, margin, maxWidth);
          break;
        case 'space':
          yPosition += 5;
          break;
      }
    });
    return yPosition;
  }

  renderHeading(doc, token, yPosition, margin, maxWidth) {
    yPosition += 8;
    
    const sizes = { 1: 18, 2: 16, 3: 14, 4: 12, 5: 11, 6: 10 };
    const fontSize = sizes[token.depth] || 12;
    
    doc.setFontSize(fontSize);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(17, 24, 39); // #111827
    
    const lines = doc.splitTextToSize(token.text, maxWidth);
    doc.text(lines, margin, yPosition);
    yPosition += lines.length * (fontSize * 0.5) + 5;

    // Add underline for h1 and h2
    if (token.depth <= 2) {
      doc.setDrawColor(token.depth === 1 ? 59 : 229, token.depth === 1 ? 130 : 231, token.depth === 1 ? 246 : 235);
      doc.line(margin, yPosition, margin + 100, yPosition);
      yPosition += 5;
    }

    return yPosition + 5;
  }

  renderParagraph(doc, token, yPosition, margin, maxWidth) {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(75, 85, 99); // #4b5563
    
    // Handle basic inline formatting
    let text = token.text
      .replace(/\*\*(.*?)\*\*/g, '$1') // Remove bold markers for now
      .replace(/\*(.*?)\*/g, '$1')     // Remove italic markers
      .replace(/`([^`]+)`/g, '$1');    // Remove inline code markers

    const lines = doc.splitTextToSize(text, maxWidth);
    doc.text(lines, margin, yPosition);
    
    return yPosition + lines.length * 6 + 8;
  }

  renderCodeBlock(doc, token, yPosition, margin, maxWidth) {
    // Background for code block
    doc.setFillColor(249, 250, 251); // #f9fafb
    doc.setDrawColor(229, 231, 235); // #e5e7eb
    
    const codeLines = token.text.split('\n');
    const lineHeight = 5;
    const padding = 5;
    const blockHeight = (codeLines.length * lineHeight) + (padding * 2);
    
    doc.rect(margin - 2, yPosition - padding, maxWidth + 4, blockHeight, 'FD');
    
    // Code text
    doc.setFontSize(9);
    doc.setFont('courier', 'normal');
    doc.setTextColor(55, 65, 81); // #374151
    
    codeLines.forEach((line, index) => {
      const trimmedLine = line.trim();
      if (trimmedLine) {
        doc.text(trimmedLine, margin, yPosition + (index * lineHeight));
      }
    });
    
    return yPosition + blockHeight + 10;
  }

  renderList(doc, token, yPosition, margin, maxWidth) {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(75, 85, 99);
    
    token.items.forEach((item, index) => {
      const bullet = token.ordered ? `${index + 1}.` : '•';
      const bulletWidth = doc.getTextWidth(bullet + ' ');
      
      // Bullet
      doc.text(bullet, margin, yPosition);
      
      // Item text
      const itemText = item.text.replace(/\*\*(.*?)\*\*/g, '$1').replace(/\*(.*?)\*/g, '$1');
      const lines = doc.splitTextToSize(itemText, maxWidth - bulletWidth);
      doc.text(lines, margin + bulletWidth, yPosition);
      
      yPosition += lines.length * 6 + 3;
    });
    
    return yPosition + 5;
  }

  renderBlockquote(doc, token, yPosition, margin, maxWidth) {
    // Left border for blockquote
    doc.setDrawColor(59, 130, 246); // #3b82f6
    doc.setFillColor(239, 246, 255); // #eff6ff
    
    const quoteText = this.extractTextFromTokens(token.tokens);
    const lines = doc.splitTextToSize(quoteText, maxWidth - 10);
    const blockHeight = lines.length * 6 + 10;
    
    // Background
    doc.rect(margin, yPosition - 3, maxWidth, blockHeight, 'F');
    
    // Left border
    doc.setLineWidth(2);
    doc.line(margin, yPosition - 3, margin, yPosition + blockHeight - 3);
    doc.setLineWidth(0.2);
    
    // Quote text
    doc.setFontSize(11);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(30, 64, 175); // #1e40af
    doc.text(lines, margin + 8, yPosition + 3);
    
    return yPosition + blockHeight + 5;
  }

  extractTextFromTokens(tokens) {
    return tokens.map(token => {
      if (token.text) return token.text;
      if (token.tokens) return this.extractTextFromTokens(token.tokens);
      return '';
    }).join(' ');
  }
}

module.exports = SimplePDFService;